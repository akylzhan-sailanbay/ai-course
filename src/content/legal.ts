// Kazakhstan (Закон РК «О персональных данных и их защите», Закон «О защите прав потребителей»),
// but they are NOT legal advice: have a lawyer review before launch (see docs/LAUNCH-CHECKLIST.md).

import type { Course, Lang } from '../config/course';
import type { Facts } from './types';
import { todo } from '../lib/placeholders';

export interface LegalDoc {
  title: string;
  note: string;
  sections: Array<{ h: string; p: string[] }>;
}

function contactLine(c: Course): string {
  const parts = [c.contacts.email, c.contacts.phone].filter(Boolean);
  return parts.length ? parts.join(', ') : todo('email или телефон для обращений');
}

